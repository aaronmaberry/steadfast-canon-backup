#!/usr/bin/env python3
"""Writes NAME-SWAP-INDEX.md: every place each swappable name appears (file:line)."""
import json, re, pathlib, datetime
root = pathlib.Path(__file__).resolve().parent.parent
cfg = json.load(open(root/'_build/names.json'))
tied = {"walksteadfast.com": r"walksteadfast\.com", "#WalkSteadfast": r"#WalkSteadfast", "@steadfastwalk (and /steadfastwalk URLs)": r"steadfastwalk"}
files = sorted(p for p in root.rglob('*.md') if p.name != 'NAME-SWAP-INDEX.md' and '_notes-raw' not in p.name)
out = ["# Name swap index", "", f"Generated by `_build/name_index.py` on {datetime.datetime.now():%Y-%m-%d %H:%M} CT. Regenerate after every batch. Swap with `python3 _build/swap_names.py KEY NEW` (dry run) then `--apply`.", ""]
def scan(label, pat):
    rx = re.compile(pat)
    rows, total = [], 0
    for f in files:
        hits = [i+1 for i, l in enumerate(open(f, encoding='utf-8')) if rx.search(l)]
        if hits:
            n = sum(len(rx.findall(l)) for l in open(f, encoding='utf-8'))
            total += n
            rows.append(f"| `{f.relative_to(root)}` | {n} | {', '.join(map(str, hits))} |")
    out.extend([f"## {label}", "", f"Total occurrences: {total}", "", "| File | Count | Lines |", "|---|---|---|", *rows, ""])
for k, v in cfg.items():
    pat = r"(?<!#)\b" + re.escape(v['value']) + r"\b" if k != 'show_name' else r"(?<!#)\bWalk Steadfast\b"
    scan(f"{k}: \"{v['value']}\" ({v['note']})", pat)
for label, pat in tied.items():
    scan(f"Tied to show name: {label}", pat)
(root/'NAME-SWAP-INDEX.md').write_text('\n'.join(out))
print('wrote NAME-SWAP-INDEX.md')
