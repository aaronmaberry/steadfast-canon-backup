#!/usr/bin/env python3
"""Generate meta/SWEEP.md, meta/SCRIPTURE-COUNT.md and meta/_stats.tsv from book/.

Run after niv_verify.py (which writes /tmp/niv-unique.json and its TSV to stdout):
  python3 niv_verify.py > /tmp/niv.tsv && python3 make_reports.py /tmp/niv.tsv
"""
from __future__ import annotations

import difflib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from checks import (  # noqa: E402
    BASE,
    BOOK,
    CREED_RE,
    DASH_RE,
    EXTRA_RE,
    SWEEP_RE,
    TRANSCRIPTS,
    margin_blocks,
    ngrams,
    strip_margins,
    words,
)

META = BOOK.parent / "meta"
MARKS = ["Stop Waiting", "Pick Up the Weight", "Go First", "Work for God's Pay"]
FOCUS = {"04": "Stop Waiting", "05": "Pick Up the Weight", "06": "Go First", "07": "Work for God's Pay"}
TARGET = {"00-introduction.md": "1", "03-the-four-marks.md": "<=2", "07-live-for-a-reward-that-lasts.md": "1",
          "34-write-the-next-move.md": "1", "35-these-men-are-my-brothers.md": "1", "wrap-back-copy.md": "1"}


def main(niv_tsv: str) -> None:
    files = sorted(BOOK.glob("*.md"))
    # ---- sweep
    out = ["# Sweep results", "",
           "Generated by `meta/tools/make_reports.py` over `book/` (44 files). All searches case-insensitive.", "",
           "## 1. Brief regex (§7.4)", "",
           "```", SWEEP_RE.pattern, "```", ""]
    total = 0
    rows = []
    for p in files:
        for n, ln in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            for m in SWEEP_RE.finditer(ln):
                total += 1
                rows.append(f"| `{p.name}` | {n} | `{m.group(0)}` |")
    out += [f"**Total hits: {total}.** Every hit is on the copyright page's locked acknowledgment line (the one allowed exception).", "",
            "| File | Line | Match |", "|---|---:|---|", *rows, ""]
    # extra fences
    ex = []
    for p in files:
        for n, ln in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
            for m in EXTRA_RE.finditer(ln):
                ex.append(f"| `{p.name}` | {n} | `{m.group(0)}` |")
    out += ["## 2. Extra fences (synonym rebuilds, course sub-points, triads, 'weeknight')", "",
            "```", EXTRA_RE.pattern, "```", "",
            f"**Total hits: {len(ex)}.**" + (" Only the copyright acknowledgment (\"Authentic Manhood\" contains \"authentic man\")." if ex else ""), ""]
    if ex:
        out += ["| File | Line | Match |", "|---|---:|---|", *ex, ""]
    # dashes
    d_prose = sum(len(DASH_RE.findall(strip_margins(p.read_text(encoding="utf-8")))) for p in files)
    d_margin = []
    for p in files:
        for _n, ref, b in margin_blocks(p.read_text(encoding="utf-8")):
            k = b.count("\u2014")
            if k:
                d_margin.append((p.name, ref.strip("*").strip(), k))
    en_margin = sum(b.count("\u2013") for p in files for _n, _r, b in margin_blocks(p.read_text(encoding="utf-8")))
    out += ["## 3. Em and en dashes", "",
            f"- Prose (everything outside `:::margin` blocks): **{d_prose}** em or en dashes.",
            f"- Margin blocks: **{sum(k for _a, _b, k in d_margin)}** em dashes, every one the NIV's own (L2), in {len(d_margin)} blocks; en dashes in margins: {en_margin}.", "",
            *[f"  - `{a}`: {b} ({k})" for a, b, k in d_margin], ""]
    # ngram
    trans = {tp.name: ngrams(words(tp.read_text(encoding="utf-8", errors="ignore").lower())) for tp in sorted(TRANSCRIPTS.glob("*.md"))}
    allg = set().union(*trans.values())
    body_runs, margin_hit_blocks, margin_blocks_total = [], [], 0
    for p in files:
        t = p.read_text(encoding="utf-8")
        bw = words(strip_margins(t).lower())
        i = 0
        while i < len(bw) - 7:
            if tuple(bw[i:i + 8]) in allg:
                j = i
                while j + 1 < len(bw) - 7 and tuple(bw[j + 1:j + 9]) in allg:
                    j += 1
                body_runs.append((p.name, " ".join(bw[i:j + 8])))
                i = j + 8
            else:
                i += 1
        for _n, ref, b in margin_blocks(t):
            margin_blocks_total += 1
            mw = words(b.lower())
            if any(tuple(mw[k:k + 8]) in allg for k in range(len(mw) - 7)):
                margin_hit_blocks.append((p.name, ref.strip("*").strip()))
    out += ["## 4. Eight-word overlap vs `biblical-manhood/transcripts/*.md`", "",
            f"Transcript files scanned: {len(trans)}. Method: every 8-word window (lowercased, `[A-Za-z0-9']+` tokens) in the book compared with every 8-word window in the transcripts.", "",
            f"- **Prose (everything outside `:::margin` blocks): {len(body_runs)} matching runs.**",
            f"- Scripture margin blocks with an 8-word match: {len(margin_hit_blocks)} of {margin_blocks_total} (Tim reading the same NIV verse; allowed).", ""]
    if body_runs:
        out += ["| File | Run |", "|---|---|", *[f"| `{a}` | {b} |" for a, b in body_runs], ""]
    out += ["Margin blocks that match a transcript (Scripture only):", "", *[f"- `{a}`: {b}" for a, b in margin_hit_blocks], "",
            "For reference: the pre-rewrite base had 49 runs, including the old creed in 9 files; the first pass ended at 0 prose runs.", ""]
    # creed + marks
    out += ["## 5. Creed count per file", "",
            "Pattern: `stops waiting, picks up the weight, goes first, and works for God's pay, not the room's`.", "",
            "| File | Creed | Target |", "|---|---:|---|"]
    for p in files:
        c = len(CREED_RE.findall(p.read_text(encoding="utf-8")))
        if c or p.name in TARGET:
            out.append(f"| `{p.name}` | {c} | {TARGET.get(p.name, '0')} |")
    others = [p.name for p in files if p.name not in TARGET and CREED_RE.search(p.read_text(encoding="utf-8"))]
    out += ["", f"Files with the creed outside the allowed list: **{len(others)}**.", "",
            "## 6. Mark-name mentions per chapter", "",
            "Case-sensitive title-case matches of the four mark names (so the plain verb \"go first\" is not counted). H1 lines count. The full creed uses verb forms and is not counted here.", "",
            "| File | Focus mark | Stop Waiting | Pick Up the Weight | Go First | Work for God's Pay |", "|---|---|---:|---:|---:|---:|"]
    for p in files:
        if not re.match(r"^\d\d-", p.name):
            continue
        t = p.read_text(encoding="utf-8")
        c = [len(re.findall(re.escape(m), t)) for m in MARKS]
        if any(c) or p.name[:2] in FOCUS:
            out.append(f"| `{p.name}` | {FOCUS.get(p.name[:2], '')} | " + " | ".join(str(x) for x in c) + " |")
    (META / "SWEEP.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    # ---- scripture
    rows = [r.split("\t") for r in Path(niv_tsv).read_text(encoding="utf-8").splitlines() if r and not r.startswith("#")]
    uniq = json.load(open("/tmp/niv-unique.json"))
    s = ["# Scripture count and NIV check", "",
         "Every `:::margin` block in `book/`, checked against the NIV (2011 text as served by Bible Gateway, `version=NIV`) on 2026-10-01 by `meta/tools/niv_verify.py`.", "",
         f"- Margin blocks: **{len(rows)}**",
         f"- Unique verses (ranges expanded): **{len(uniq)}**, under Biblica's 500-verse gratis limit. No complete book of the Bible is quoted. Scripture in margin blocks is about 6% of the book's words, far under the 25% limit.",
         "- Every block's reference line reads `**Book C:V NIV**`.", "",
         "Rule (Aaron, 2026-10-01; SECOND-PASS-BRIEF L2): each block reproduces the NIV 2011 word for word and punctuation for punctuation, including the NIV's own em dashes. The only allowance is that a dangling quotation mark at the very start or end of a block, belonging to speech that opens or closes outside the cited verses, may be dropped. Marks are never added, and nested single quotes stay single.",
         "",
         "Comparison is raw against the NIV, with two typographic normalizations on the NIV side. Curly quotes become straight, since the manuscript uses straight quotes throughout and the binder or typesetter can curl them. Spaces around an em dash are closed up: Bible Gateway and BibleHub show a space after a dash only where a verse number follows (Ephesians 2:8 \"gift of God\u2014 9 not by works\"), and the NIV closes its dashes in running text (\"faith\u2014and\"). So Ephesians 2:8-9 prints \"God\u2014not by works\". Please confirm this against a print NIV (OPEN-QUESTIONS).",
         "",
         "Status key:",
         "- **EXACT**: identical to the NIV text of the cited verses.",
         "- **EXACT-EDGE-DROP (...)**: identical once the named dangling edge mark(s) are dropped.",
         "- **EXCERPT (...)**: a contiguous, word-for-word part of the cited verses, with any dangling edge mark at the cut noted.",
         "",
         "Some blocks end with an open quotation mark, exactly as the NIV prints them, because the cited verse leaves the speech running into the next verse and marks are never added: 1 Kings 2:2-3, 2 Samuel 12:7, 2 Samuel 12:13, Amos 7:7-8, John 4:34, 1 Samuel 17:34-35.",
         "",
         "| File | Line | Reference | Status | Verses |", "|---|---:|---|---|---:|"]
    from niv_verify import expand
    for r in rows:
        f, ln, ref, st = r[0], r[1], r[2], r[3]
        s.append(f"| `{f}` | {ln} | {ref} | {st} | {len(expand(ref))} |")
    s += ["", "## Unique verses", "", ", ".join(sorted(uniq, key=lambda v: (v.split(' ')[0], v))), ""]
    (META / "SCRIPTURE-COUNT.md").write_text("\n".join(s) + "\n", encoding="utf-8")

    # ---- stats
    from checks import FIRST
    st = ["file\tbase\tfirst_pass\tsecond_pass\tvs_first\tvs_base\tsim_vs_first\th1_changed_vs_first"]
    for p in files:
        b = BASE / p.name
        new_t = p.read_text(encoding="utf-8")
        old_t = b.read_text(encoding="utf-8") if b.exists() else ""
        ow, nw = words(old_t.lower()), words(new_t.lower())
        sim = difflib.SequenceMatcher(None, ow, nw, autojunk=False).ratio()
        npw = words(strip_margins(new_t).lower())
        og = ngrams(words(strip_margins(old_t).lower()), 6)
        ng = [tuple(npw[i:i + 6]) for i in range(len(npw) - 5)]
        reuse = sum(1 for g in ng if g in og) / max(1, len(ng))
        fp_t = (FIRST / p.name).read_text(encoding="utf-8") if (FIRST / p.name).exists() else ""
        fw = words(fp_t.lower())
        sim_f = difflib.SequenceMatcher(None, fw, nw, autojunk=False).ratio()
        h1 = "yes" if (fp_t.splitlines()[:1] != new_t.splitlines()[:1]) else "no"
        st.append(f"{p.name}\t{len(ow)}\t{len(fw)}\t{len(nw)}\t{len(nw)-len(fw):+d}\t{len(nw)-len(ow):+d}\t{sim_f:.2f}\t{h1}")
    (META / "_stats.tsv").write_text("\n".join(st) + "\n", encoding="utf-8")
    print("wrote SWEEP.md, SCRIPTURE-COUNT.md, _stats.tsv")


if __name__ == "__main__":
    main(sys.argv[1])
